const TABLES: Record<AppLanguage, Record<UiKey, string>> = {
  en: EN,
  es: ES,
  fr: FR,
};

function interpolate(template: string, vars?: UiVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translateUi(language: unknown, key: UiKey, vars?: UiVars): string {
  const lang = normalizeAppLanguage(language);
  return interpolate(TABLES[lang][key] ?? EN[key], vars);
}

export function greetingForHour(language: AppLanguage, hour: number): string {
  if (hour < 12) return translateUi(language, 'home.goodMorning');
  if (hour < 17) return translateUi(language, 'home.goodAfternoon');
  return translateUi(language, 'home.goodEvening');
}

