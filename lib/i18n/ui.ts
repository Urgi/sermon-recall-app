const TABLES: Record<AppLanguage, Record<UiKey, string>> = {
  en: EN,
  es: ES,
  fr: FR,
};

function interpolate(template: string, vars?: UiVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translateUi(language: unknown, key: UiKey, vars?: UiVars): string {
  const lang = normalizeAppLanguage(language);
  // Singular variant: `foo.bar` + `foo.barOne` when `count` is exactly 1.
  const oneKey = `${key}One` as UiKey;
  const useOne = vars?.count === 1 && oneKey in EN;
  const k = useOne ? oneKey : key;
  return interpolate(TABLES[lang][k] ?? EN[k], vars);
}

/**
 * Language for code outside React (error mappers, toast copy, date helpers).
 * `I18nProvider` keeps this in sync; components still read it through `useI18n()`
 * so they re-render when it changes.
 */
let activeUiLanguage: AppLanguage = DEFAULT_APP_LANGUAGE;

export function setActiveUiLanguage(language: AppLanguage): void {
  activeUiLanguage = language;
}

export function getActiveUiLanguage(): AppLanguage {
  return activeUiLanguage;
}

/** Date/number locale for the active UI language. */
export function uiLocale(): string {
  return localeForLanguage(activeUiLanguage);
}

/** Translate using the active UI language (for non-component code). */
export function tr(key: UiKey, vars?: UiVars): string {
  return translateUi(activeUiLanguage, key, vars);
}

export function greetingForHour(language: AppLanguage, hour: number): string {
  if (hour < 12) return translateUi(language, 'home.goodMorning');
  if (hour < 17) return translateUi(language, 'home.goodAfternoon');
  return translateUi(language, 'home.goodEvening');
}

